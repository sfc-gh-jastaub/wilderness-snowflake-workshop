USE ROLE ACCOUNTADMIN;

EXECUTE IMMEDIATE FROM @WILDERNESS_HOL.SETUP.WORKSHOP_REPO/branches/main/setup/11_infrastructure.sql;
EXECUTE IMMEDIATE FROM @WILDERNESS_HOL.SETUP.WORKSHOP_REPO/branches/main/setup/12_generate_structured.sql;
EXECUTE IMMEDIATE FROM @WILDERNESS_HOL.SETUP.WORKSHOP_REPO/branches/main/setup/13_load_feedback.sql;
EXECUTE IMMEDIATE FROM @WILDERNESS_HOL.SETUP.WORKSHOP_REPO/branches/main/setup/14_semantic_view.sql;
EXECUTE IMMEDIATE FROM @WILDERNESS_HOL.SETUP.WORKSHOP_REPO/branches/main/setup/15_email.sql;
EXECUTE IMMEDIATE FROM @WILDERNESS_HOL.SETUP.WORKSHOP_REPO/branches/main/setup/16_lab3_production.sql;

SELECT 'RAW.DIM_STORE' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM WILDERNESS_HOL.RAW.DIM_STORE
UNION ALL SELECT 'RAW.DIM_PRODUCT', COUNT(*) FROM WILDERNESS_HOL.RAW.DIM_PRODUCT
UNION ALL SELECT 'RAW.DIM_MEMBER', COUNT(*) FROM WILDERNESS_HOL.RAW.DIM_MEMBER
UNION ALL SELECT 'RAW.FCT_SALES_LINE', COUNT(*) FROM WILDERNESS_HOL.RAW.FCT_SALES_LINE
UNION ALL SELECT 'RAW.FCT_RETURN', COUNT(*) FROM WILDERNESS_HOL.RAW.FCT_RETURN
UNION ALL SELECT 'RAW.FCT_INVENTORY', COUNT(*) FROM WILDERNESS_HOL.RAW.FCT_INVENTORY
UNION ALL SELECT 'RAW.CUSTOMER_FEEDBACK', COUNT(*) FROM WILDERNESS_HOL.RAW.CUSTOMER_FEEDBACK;
